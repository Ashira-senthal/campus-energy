"""
Report figures for the written report and `reports/figures/`.

Plotting lives outside the Streamlit app on purpose: the dashboard draws its own
interactive Plotly charts, while these static PNGs are what go into the report
and the slides, so they can be regenerated by one command.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # headless: works over SSH and in CI
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import seaborn as sns  # noqa: E402
import shap  # noqa: E402

sns.set_theme(style="whitegrid", context="talk")


def _save(fig: plt.Figure, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(path, dpi=130, bbox_inches="tight")
    plt.close(fig)
    return path


def hour_weekday_heatmaps(hourly: pd.DataFrame, out_dir: Path) -> Path:
    """One hour x weekday mean-load heatmap per building.

    This is the single most useful EDA picture for energy data: the weekly
    working rhythm (occupancy) is visible as a bright block on weekday mornings.
    """
    buildings = hourly["building_label"].unique()
    fig, axes = plt.subplots(2, 2, figsize=(14, 9))
    for ax, label in zip(axes.ravel(), buildings):
        subset = hourly[hourly["building_label"] == label]
        pivot = subset.pivot_table(
            index="dayofweek", columns="hour", values="electricity", aggfunc="mean"
        )
        sns.heatmap(
            pivot,
            ax=ax,
            cmap="magma",
            cbar_kws={"label": "mean kWh"},
            yticklabels=["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"],
        )
        ax.set_title(label, fontsize=11)
        ax.set_xlabel("hour of day")
        ax.set_ylabel("")
    fig.suptitle("Normal weekly rhythm: mean electricity (kWh) by hour and weekday")
    return _save(fig, out_dir / "01_hour_weekday_heatmaps.png")


def daily_profiles(hourly: pd.DataFrame, out_dir: Path) -> Path:
    """Average daily shape on weekdays vs weekends, all buildings."""
    fig, axes = plt.subplots(2, 2, figsize=(14, 9))
    for ax, label in zip(axes.ravel(), hourly["building_label"].unique()):
        subset = hourly[hourly["building_label"] == label]
        for flag, name, colour in [
            (0, "weekday", "#1f77b4"),
            (1, "weekend", "#d62728"),
        ]:
            profile = (
                subset[subset["is_weekend"] == flag]
                .groupby("hour")["electricity"]
                .mean()
            )
            ax.plot(profile.index, profile.values, marker="o", ms=3, label=name, color=colour)
        ax.set_title(label, fontsize=11)
        ax.set_xlabel("hour of day")
        ax.set_ylabel("mean kWh")
        ax.legend(fontsize=9)
    fig.suptitle("Weekday vs weekend daily profile")
    return _save(fig, out_dir / "02_daily_profiles.png")


def load_vs_temperature(hourly: pd.DataFrame, out_dir: Path) -> Path:
    """Load against outdoor temperature, with a binned mean line.

    A U-shape (or a rising tail above ~24 C) is the fingerprint of cooling load;
    the flat middle is baseload. This motivates using temperature as a feature.
    """
    fig, axes = plt.subplots(2, 2, figsize=(14, 9))
    for ax, label in zip(axes.ravel(), hourly["building_label"].unique()):
        subset = hourly[hourly["building_label"] == label].dropna(
            subset=["electricity", "airTemperature"]
        )
        ax.scatter(
            subset["airTemperature"],
            subset["electricity"],
            s=3,
            alpha=0.15,
            color="#4c72b0",
            linewidths=0,
        )
        bins = pd.cut(subset["airTemperature"], bins=20)
        trend = subset.groupby(bins, observed=True).agg(
            temp=("airTemperature", "mean"), kwh=("electricity", "mean")
        )
        ax.plot(trend["temp"], trend["kwh"], color="#c44e52", lw=2, label="binned mean")
        ax.set_title(label, fontsize=11)
        ax.set_xlabel("air temperature (C)")
        ax.set_ylabel("hourly kWh")
        ax.legend(fontsize=9)
    fig.suptitle("Load vs outdoor temperature")
    return _save(fig, out_dir / "03_load_vs_temperature.png")


def monthly_trend(hourly: pd.DataFrame, out_dir: Path) -> Path:
    """Monthly mean load per building -- seasonality and term-time effects."""
    subset = hourly.dropna(subset=["electricity"]).copy()
    subset["month_start"] = subset["timestamp"].dt.to_period("M").dt.to_timestamp()
    trend = (
        subset.groupby(["month_start", "building_label"])["electricity"]
        .mean()
        .reset_index()
    )
    fig, ax = plt.subplots(figsize=(12, 5))
    for label, group in trend.groupby("building_label"):
        ax.plot(group["month_start"], group["electricity"], marker="o", label=label)
    ax.set_ylabel("mean hourly kWh")
    ax.set_xlabel("month")
    ax.set_yscale("log")
    ax.set_title("Monthly mean load (log scale: 37x range between buildings)")
    ax.legend(fontsize=9)
    return _save(fig, out_dir / "04_monthly_trend.png")


def shap_summary(
    shap_values: np.ndarray,
    features: pd.DataFrame,
    out_dir: Path,
    building_label: str,
) -> Path:
    """SHAP beeswarm: direction and size of each feature's effect."""
    fig = plt.figure(figsize=(10, 7))
    shap.summary_plot(shap_values, features, show=False, max_display=14)
    plt.title(f"SHAP summary - {building_label}", fontsize=12)
    return _save(fig, out_dir / f"05_shap_summary_{building_label.split(' ')[0]}.png")


def make_all(hourly: pd.DataFrame, out_dir: Path) -> list[Path]:
    """Generate every static EDA figure in one call."""
    return [
        hour_weekday_heatmaps(hourly, out_dir),
        daily_profiles(hourly, out_dir),
        load_vs_temperature(hourly, out_dir),
        monthly_trend(hourly, out_dir),
    ]
