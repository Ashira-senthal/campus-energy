"""
Page 9: Data & Quality.
Telemetry provenance, cleaning protocol, feature engineering, and data sample preview.
"""

from __future__ import annotations

import streamlit as st
import pandas as pd
import numpy as np

from components import (
    ce_page_header,
    ce_kpi_strip,
    ce_metric_row,
    ce_table,
    ce_source_note,
    ce_empty_message,
)
from theme import fig_data_coverage, render_chart
from data import (
    get_building_catalog,
    load_csv_report,
    load_parquet,
)

def render(ctx: dict):
    st.markdown(
        ce_page_header(
            "Data & Quality",
            "Data provenance, BDG2 source integrity, cleaning protocols, and telemetry quality audit.",
        ),
        unsafe_allow_html=True,
    )

    catalog = get_building_catalog()
    quality_df = load_csv_report("building_quality")

    # KPI Strip (4 numbers)
    tot_hours = 17544
    tot_blds = len(catalog)

    pct_complete = 100.0
    if not quality_df.empty:
        pct_complete = float(quality_df["pct_complete_after_repair"].mean())
        missing_pct = 100.0 - pct_complete
    else:
        missing_pct = 0.0

    kpis_html = "".join([
        ce_metric_row("Hours Covered", f"{tot_hours:,}", unit="h", delta="2 full years (2016–2017)", delta_kind="neutral", source="data/raw/electricity_cleaned.csv"),
        ce_metric_row("Monitored Buildings", f"{tot_blds}", delta="Fox education cohort", delta_kind="neutral", source="reports/building_coverage.csv"),
        ce_metric_row("Missing Unfilled", f"{missing_pct:.3f}%", delta="99.998% complete after repair", delta_kind="pass", source="reports/building_quality.csv"),
        ce_metric_row("Date Range", "2016 → 2017", delta="24 chronological months", delta_kind="neutral", source="hourly.parquet"),
    ])
    st.markdown(ce_kpi_strip(kpis_html), unsafe_allow_html=True)

    # Primary View: Data Coverage Chart
    st.markdown("<h4 style='font-size: 17px; margin-bottom: 8px;'>Telemetry Presence & Repair Status by Building</h4>", unsafe_allow_html=True)
    if not quality_df.empty:
        fig_cov = fig_data_coverage(quality_df)
        render_chart(fig_cov, key="data_coverage")
        st.markdown(ce_source_note("reports/building_quality.csv (generated by src/features.py)"), unsafe_allow_html=True)
    else:
        st.markdown(ce_empty_message("reports/building_quality.csv not found."), unsafe_allow_html=True)

    st.markdown("<div style='margin-top: 24px;'></div>", unsafe_allow_html=True)

    # Tabs: Source | Cleaning | Features | Sample Preview
    tab_src, tab_clean, tab_feat, tab_sample = st.tabs([
        "Source & Provenance",
        "Cleaning Protocol",
        "Feature Definitions",
        "Sample Data Preview",
    ])

    with tab_src:
        st.markdown("<h4 style='font-size: 17px; margin-bottom: 8px;'>Building Data Genome Project 2 (BDG2) Details</h4>", unsafe_allow_html=True)

        src_table = [
            ("Dataset Name", "Building Data Genome Project 2 (BDG2)"),
            ("Publisher & Paper", "Miller et al. (Scientific Data, 2020), BUDS Lab, NUS"),
            ("License", "Open Data Commons Open Database License (ODbL)"),
            ("Site Selected", "Fox (chosen from 19 sites for having 56 usable education facilities across 5 usage types)"),
            ("Raw Meters File", "data/meters/cleaned/electricity_cleaned.csv (~166.9 MB, 17,544 rows × 1,578 buildings)"),
            ("Raw Weather File", "data/weather/weather.csv (~18.6 MB, 331,166 rows long)"),
            ("Raw Metadata File", "data/metadata/metadata.csv (~0.3 MB, 1,636 buildings)"),
            ("Download Script", "src/download_data.py (downloads from Git LFS media endpoint with SHA-256 size checks)"),
        ]
        st.markdown(ce_table(["Attribute", "Specification"], src_table, source="PROJECT_GUIDE.md Section 4"), unsafe_allow_html=True)

    with tab_clean:
        st.markdown("<h4 style='font-size: 17px; margin-bottom: 8px;'>Cleaning Pipeline (src/features.py clean_panel)</h4>", unsafe_allow_html=True)

        if not quality_df.empty:
            q_headers = ["Building ID", "Total Hours", "Raw Present", "Repaired Gaps (≤3h)", "Unfilled Missing", "Final Completeness %", "Zero Hours"]
            q_rows = []
            for _, r in quality_df.iterrows():
                q_rows.append([
                    r["building_id"],
                    f"{r['hours_total']:,}",
                    f"{r['hours_raw_present']:,}",
                    f"{r['hours_imputed']:,}",
                    f"{r['hours_still_missing']:,}",
                    f"{r['pct_complete_after_repair']:.3f}%",
                    f"{r['zero_hours']:,}",
                ])
            st.markdown(ce_table(q_headers, q_rows, source="reports/building_quality.csv"), unsafe_allow_html=True)

        st.markdown("""
<div style="font-size: 15px; color: var(--text); line-height: 1.6; background: var(--surface); border: 1px solid var(--border); border-radius: 6px; padding: 16px; margin-top: 12px;">
  <b>Three-Stage Cleaning Rules:</b>
  <ol style="margin: 0; padding-left: 20px;">
    <li><b>Full Calendar Reindexing:</b> The raw time series is reindexed to an unbroken hourly grid between 2016-01-01 00:00 and 2017-12-31 23:00 (17,544 timestamps). This ensures that autoregressive lag shifts represent true elapsed time.</li>
    <li><b>Negative Value Masking:</b> Negative energy readings are physically impossible and are converted to <code>NaN</code>.</li>
    <li><b>Bounded Linear Interpolation:</b> Gaps of at most <code>MAX_INTERP_GAP_HOURS = 3</code> are linearly interpolated to prevent comms dropouts from punching holes in lag features. Gaps longer than 3 hours remain strictly <code>NaN</code> to avoid fabricating synthetic telemetry.</li>
  </ol>
</div>
""", unsafe_allow_html=True)

    with tab_feat:
        st.markdown("<h4 style='font-size: 17px; margin-bottom: 8px;'>Engineered Input Feature Schema</h4>", unsafe_allow_html=True)
        feat_rows = [
            ("hour", "Calendar", "Hour of day (0–23)"),
            ("dayofweek", "Calendar", "Day of week (0=Mon, 6=Sun)"),
            ("month", "Calendar", "Month of year (1–12)"),
            ("is_weekend", "Calendar", "Binary indicator (1 for Saturday/Sunday)"),
            ("is_holiday", "Calendar", "US federal holiday indicator"),
            ("hour_sin, hour_cos", "Calendar", "Cyclical sine/cosine transformation for 24h periodicity"),
            ("doy_sin, doy_cos", "Calendar", "Cyclical sine/cosine transformation for 365-day solar cycle"),
            ("airTemperature", "Weather", "Dry-bulb ambient temperature in °C"),
            ("dewTemperature", "Weather", "Dew point temperature in °C"),
            ("cloudCoverage", "Weather", "Oktas cloud cover measurement (0–8)"),
            ("windSpeed", "Weather", "Wind speed in m/s"),
            ("precipDepth1HR", "Weather", "Hourly precipitation accumulation in mm"),
            ("temp_roll_24", "Weather", "Trailing 24-hour rolling mean temperature for building thermal mass"),
            ("kwh_lag_24", "History", "Measured load at t - 24 hours (yesterday same hour)"),
            ("kwh_lag_48", "History", "Measured load at t - 48 hours (day before yesterday)"),
            ("kwh_lag_168", "History", "Measured load at t - 168 hours (same hour last week)"),
            ("kwh_roll_mean_24", "History", "Trailing 24h load mean over [t-48h, t-24h]"),
            ("kwh_roll_mean_168", "History", "Trailing 168h load mean over [t-192h, t-24h]"),
            ("kwh_roll_std_24", "History", "Trailing 24h load volatility over [t-48h, t-24h]"),
            ("kwh_roll_std_168", "History", "Trailing 168h load volatility over [t-192h, t-24h]"),
        ]
        st.markdown(ce_table(["Feature Name", "Domain", "Description"], feat_rows, source="src/features.py"), unsafe_allow_html=True)

    with tab_sample:
        st.markdown("<h4 style='font-size: 17px; margin-bottom: 8px;'>Paginated Telemetry Preview (data/processed/hourly.parquet)</h4>", unsafe_allow_html=True)
        hourly_df = load_parquet("hourly")
        if not hourly_df.empty:
            sample_page = st.number_input("Sample Page", min_value=1, max_value=len(hourly_df)//25, value=1, step=1, key="sample_page_num")
            start_i = (sample_page - 1) * 25
            slice_df = hourly_df.iloc[start_i : start_i + 25]

            p_headers = ["Timestamp", "Building", "Load (kWh)", "Air Temp (°C)", "Hour", "DoW", "Weekend", "Holiday"]
            p_rows = []
            for _, r in slice_df.iterrows():
                p_rows.append([
                    pd.to_datetime(r["timestamp"]).strftime("%Y-%m-%d %H:%M"),
                    r.get("building_label", r["building_id"]),
                    f"{r['electricity']:.2f}",
                    f"{r.get('airTemperature', np.nan):.1f}",
                    str(r.get("hour", "")),
                    str(r.get("dayofweek", "")),
                    str(r.get("is_weekend", "")),
                    str(r.get("is_holiday", "")),
                ])
            st.markdown(ce_table(p_headers, p_rows, source="data/processed/hourly.parquet"), unsafe_allow_html=True)
        else:
            st.markdown(ce_empty_message("data/processed/hourly.parquet not found."), unsafe_allow_html=True)
